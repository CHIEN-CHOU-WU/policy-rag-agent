"""Streamlit web app: ``uv run streamlit run src/policy_rag/app.py``.

A thin front end: answers come from the same ``answer_question`` (RAG) and
``run_agent`` (agent) used by the CLI, so the app adds display only.
"""

import os
from dataclasses import dataclass, field, replace

import streamlit as st

from policy_rag.agent import AgentStep, describe_step, run_agent
from policy_rag.config import Settings, load_settings
from policy_rag.llm.base import LLMClient, LLMError
from policy_rag.llm.factory import PROVIDERS, create_llm_client
from policy_rag.rag import answer_question
from policy_rag.store.factory import create_page_store, create_vector_store
from policy_rag.tools import PolicyTools

EXAMPLES = [
    "How do I add dental coverage?",
    "What's the penalty if I sign up for Part B late?",
    "Can I change my Medicare Advantage Plan in February?",
]
MODES = {"agent": "Agent — researches with tools", "rag": "RAG — searches once"}
PROVIDER_LABELS = {"ollama": "Ollama (local, free)", "gemini": "Google Gemini", "anthropic": "Claude"}
DISCLAIMER = (
    "Demonstration only. Answers are generated by an AI model from the public "
    "*Medicare & You 2027* handbook and are not insurance, legal, or medical advice."
)


@dataclass
class Reply:
    """An answer as the page shows it, kept in session state so history re-renders."""

    text: str
    sources: list[tuple[str, str]] = field(default_factory=list)
    steps: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    error: str | None = None


@st.cache_resource
def get_tools() -> PolicyTools:
    settings = load_settings()
    return PolicyTools(create_vector_store(settings), create_page_store(settings))


@st.cache_resource
def get_llm(provider: str) -> LLMClient:
    return create_llm_client(replace(load_settings(), llm_provider=provider))


def has_credentials(settings: Settings, provider: str) -> bool:
    match provider:
        case "gemini":
            return bool(settings.gemini_api_key)
        case "anthropic":
            return bool(os.getenv("ANTHROPIC_API_KEY"))
        case _:
            return True


def ask(question: str, mode: str, provider: str, tools: PolicyTools) -> Reply:
    try:
        llm = get_llm(provider)
        if mode == "agent":
            with st.status("Researching the handbook…", expanded=True) as status:
                answer = run_agent(question, llm, tools, on_step=_show_step)
                count = len(answer.steps)
                status.update(
                    label=f"Researched in {count} step{'' if count == 1 else 's'}",
                    state="complete",
                    expanded=False,
                )
            reply = Reply(
                answer.text,
                sources=[(f"p. {page}", label) for page, label in answer.cited_sources],
                steps=[describe_step(step) for step in answer.steps],
            )
        else:
            with st.spinner("Searching the handbook…"):
                answer = answer_question(question, tools.store, llm)
            reply = Reply(
                answer.text,
                sources=[
                    (f"p. {source.chunk.page_label}", source.chunk.section_title)
                    for source in answer.cited_sources
                ],
            )
    except LLMError as error:
        return Reply("", error=str(error))

    if answer.is_uncited:
        reply.warnings.append("This answer cites no pages, so it can't be checked against the handbook.")
    if answer.unsupported_pages:
        pages = ", ".join(str(page) for page in answer.unsupported_pages)
        reply.warnings.append(f"The answer cites page(s) {pages}, which its sources never showed.")
    return reply


def _choose_example(example: str) -> None:
    st.session_state["example"] = example


def _show_step(step: AgentStep) -> None:
    st.write(f"🔎 `{describe_step(step)}`")


def render(reply: Reply) -> None:
    if reply.error:
        st.error(reply.error)
        return
    st.markdown(reply.text)
    if reply.sources:
        unique = dict.fromkeys(f"**{page}** — {section}" for page, section in reply.sources)
        st.caption("Sources")
        st.markdown("\n".join(f"- {line}" for line in unique))
    if reply.steps:
        with st.expander(f"Research steps ({len(reply.steps)})"):
            st.markdown("\n".join(f"{n}. `{step}`" for n, step in enumerate(reply.steps, start=1)))
    for warning in reply.warnings:
        st.warning(warning)


def main() -> None:
    st.set_page_config(page_title="Medicare Policy Assistant", page_icon="📘")
    settings = load_settings()

    with st.sidebar:
        st.header("Settings")
        mode = st.radio("Mode", list(MODES), format_func=MODES.get)
        provider = st.selectbox(
            "Model",
            PROVIDERS,
            index=PROVIDERS.index(settings.llm_provider) if settings.llm_provider in PROVIDERS else 0,
            format_func=lambda p: PROVIDER_LABELS[p] + ("" if has_credentials(settings, p) else " — no API key"),
        )
        st.caption("Each question is answered on its own; follow-ups don't see earlier answers.")
        st.divider()
        st.caption(DISCLAIMER)

    st.title("📘 Medicare Policy Assistant")
    st.caption("Ask about *Medicare & You 2027*. Every answer cites the handbook pages it comes from.")

    tools = get_tools()
    if tools.store.count() == 0:
        st.error("The document index is empty. Run `uv run python -m policy_rag.ingest` first.")
        st.stop()

    history: list[tuple[str, Reply]] = st.session_state.setdefault("history", [])
    for question, reply in history:
        st.chat_message("user").markdown(question)
        with st.chat_message("assistant"):
            render(reply)

    # An example button stores its question before the rerun it triggers.
    question = st.chat_input("Ask about coverage, costs, or enrollment…") or st.session_state.pop(
        "example", None
    )
    # The examples live in their own slot. Emptying it as soon as a question
    # arrives removes them at once; otherwise Streamlit would keep them on
    # screen, faded, until the model finishes answering.
    examples = st.empty()
    if question:
        examples.empty()
        st.chat_message("user").markdown(question)
        with st.chat_message("assistant"):
            reply = ask(question, mode, provider, tools)
            render(reply)
        history.append((question, reply))
    elif not history:
        with examples.container():
            st.write("Try one of these:")
            for example in EXAMPLES:
                st.button(example, width="stretch", on_click=_choose_example, args=(example,))


main()
